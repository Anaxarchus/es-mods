// Writes data/corporations.txt: the spaceport news items the mod shows
// (src/Press.dados). Each is shown while the condition "corporations: news
// <key>" is at least "days since epoch", so the mod shows one with a single
// set_condition (no data change, nothing added to the pilot file) and it hides
// itself when the day passes.
// - canonical companies: "<name> tender", "<name> fire", "<name> beats",
//   near the company's home system (from src/Names.dados and test/galaxy.json);
// - loss spikes: "losses <system>" near each stocked shipyard system;
// - "slot 1".."slot 4": no place or message; the mod gives them both with a
//   data change, for invented companies.
//   node mods/corporations/tools/make-news.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const MOD = join(HERE, "..");
const names = readFileSync(join(MOD, "src/Names.dados"), "utf8");
const list = (key) => JSON.parse(new RegExp(`\\[\\]string ${key} = (\\[.*\\])`).exec(names)[1]);
const canon = list("canon_names"), homes = list("canon_homes");
const galaxy = JSON.parse(readFileSync(join(MOD, "test/galaxy.json"), "utf8"));
const human = new Set(["Republic", "Free Worlds", "Syndicate", "Pirate", "Independent", "Militia"]);
const yards = [...new Set(Object.values(galaxy.planets).filter((p) => p.shipyard?.length && human.has(galaxy.systems[p.system]?.government)).map((p) => p.system))].sort();

const out = [
	"# GENERATED by tools/make-news.mjs; do not edit by hand.",
	"# Corporations keeps its market with the pilot (mod API 6 storage). This file",
	"# holds only its spaceport news items (src/Press.dados): each shows while its",
	"# condition \"corporations: news <key>\" is at least \"days since epoch\".",
	"",
	"phrase \"corporations: speakers\"",
	"\tword",
	"\t\t\"Exchange correspondent\"",
	"\t\t\"Shipyard worker\"",
	"\t\t\"Broker\"",
	"\t\t\"Freight agent\"",
	"",
];
function item(key, system, message) {
	out.push(`news "corporations: ${key}"`);
	if (system) out.push("\tlocation", `\t\tnear "${system}" 2`);
	out.push("\tname", "\t\tphrase", "\t\t\t\"corporations: speakers\"");
	if (message) out.push("\tmessage", "\t\tword", `\t\t\t\`${message}\``);
	out.push("\tto show", `\t\t"corporations: news ${key}" >= "days since epoch"`, "");
}
const possessive = (n) => (n.endsWith("s") ? n + "'" : n + "'s");
const KINDS = {
	tender: (n, home) => `${n} has won a military tender. The yards on ${home} are hiring every welder they can find.`,
	fire: (n, home) => `A fire has shut part of ${possessive(n)} works on ${home}. Crews are still clearing the wreckage, and hull deliveries will be late.`,
	beats: (n) => `${n} has posted far better earnings than last time. Its shares are the talk of the exchange.`,
};
for (let i = 0; i < canon.length; i++) {
	const system = galaxy.planets[homes[i]]?.system;
	if (!system) throw new Error(`no system for ${homes[i]}`);
	for (const [kind, text] of Object.entries(KINDS)) item(`${canon[i]} ${kind}`, system, text(canon[i], homes[i]));
}
for (const s of yards) item(`losses ${s}`, s, "Insurers say ships are being lost around here faster than at any time in years. The shipyards nearby can hardly keep hulls on their shelves.");
for (let k = 1; k <= 4; k++) item(`slot ${k}`, "", "");
writeFileSync(join(MOD, "data/corporations.txt"), out.join("\n"));
console.log(`wrote data/corporations.txt: ${canon.length * 3} company items, ${yards.length} loss items, 4 slots`);
