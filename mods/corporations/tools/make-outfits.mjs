// Writes src/Outfits.dados (M3): the canonical outfit makers' product lines
// (their "<brand> Basics" and "<brand> Advanced" outfitters in the game's
// data) and the planets that sell them. Refits (src/Refits.dados) offers a
// maker's refit line on those planets; on a game with Mod API 10's outfit
// stock, a maker in trouble leaves its outfits short there.
//   node mods/corporations/tools/make-outfits.mjs <endless-sky>/data
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { readAll } from "./es-data.mjs";

const root = process.argv[2];
if (!root) throw new Error("usage: make-outfits.mjs <game data folder>");
// Brand (as the data names its outfitters) -> canonical company (Names).
const BRANDS = { "Deep Sky": "Deep Sky", "Lovelace": "Lovelace Labs", "Delta V": "Delta V Corporation", "Syndicate": "Syndicated Systems", "Kraz": "Kraz Cybernetics" };
const all = readAll(root);
const lists = {}, planets = {};
for (const [, ls] of all) {
	let kind = null, name = null;
	for (const [indent, t] of ls) {
		if (indent === 0) { kind = t[0]; name = t[1]; continue; }
		if (kind === "outfitter" && indent === 1 && name) (lists[name] ??= new Set()).add(t[0]);
		if (kind === "planet" && indent === 1 && t[0] === "outfitter" && t[1]) (planets[t[1]] ??= new Set()).add(name);
	}
}
const companies = [], outfits = [], where = [];
for (const [brand, company] of Object.entries(BRANDS)) {
	const o = new Set(), p = new Set();
	for (const level of ["Basics", "Advanced"]) {
		for (const x of lists[`${brand} ${level}`] ?? []) o.add(x);
		for (const x of planets[`${brand} ${level}`] ?? []) p.add(x);
	}
	if (!o.size) throw new Error(`no outfitter for ${brand}`);
	companies.push(company);
	outfits.push([...o].sort().join(";"));
	where.push([...p].sort().join(";"));
}
const out = [
	"class Outfits",
	"",
	"// GENERATED by tools/make-outfits.mjs from the game's data; do not edit by hand.",
	"// Run: node mods/corporations/tools/make-outfits.mjs <endless-sky>/data",
	"//",
	"// The canonical outfit makers' product lines (their Basics and Advanced",
	"// outfitters) and the planets that sell them, joined by \";\" (Refits).",
	"",
	`[]string companies = ${JSON.stringify(companies)}`,
	`[]string lines = ${JSON.stringify(outfits)}`,
	`[]string planets = ${JSON.stringify(where)}`,
	"",
];
const file = join(dirname(fileURLToPath(import.meta.url)), "../src/Outfits.dados");
writeFileSync(file, out.join("\n"));
console.log(`wrote ${file}: ${companies.length} makers, ${outfits.map((x) => x.split(";").length).join("/")} outfits, ${where.map((x) => x.split(";").length).join("/")} planets`);
