#!/usr/bin/env python3
"""Writes mods/diplomacy/data/diplomacy fw veteran.txt, the "Free Worlds Veteran" start.

  python3 mods/diplomacy/tools/fw-veteran/emit.py <endless-sky>/data [output]

It replays the campaign path in path.py (see campaign.py) and writes a start whose intro
conversation applies every event and reputation change of that path in order, and whose
conditions are the ones the path leaves set. Standard library only (Python 3.8+)."""
import os
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from campaign import Campaign  # noqa: E402
from esdata import parse, quote as q, walk  # noqa: E402
import path as P  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'data', 'diplomacy fw veteran.txt'))

# The start's own choices (see README.md, "Quick start").
CREDITS = 5000000   # FW Syndicate Extremists 1C: Parliament's commendation, paid the day the campaign ends
SHIP_NAME = 'Second Chance'
# Diplomacy's event (data/diplomacy.txt) adding the Navy Advanced yard to Luna.
LUNA_EVENT = 'diplomacy: luna navy yard'
OSPREY = ['"Plasma Cannon" 4', '"Quad Blaster Turret"', '"Heavy Anti-Missile Turret"', '',
	'"Breeder Reactor"', '"LP036a Battery Pack"', '"D41-HY Shield Generator"', '"Large Radar Jammer"',
	'"Liquid Helium Cooler"', '"Laser Rifle" 3', '', '"Impala Plasma Thruster"', '"Impala Plasma Steering"',
	'"Jump Drive"']


def final_conditions(c):
	"""The plain conditions (not reputations) the path sets, with their final values, in first-set order."""
	vals, order = {}, []
	for d, s, k, v, src in c.timeline:
		if k != 'cond' or v[0].startswith('reputation: '):
			continue
		name = v[0]
		if name not in vals:
			order.append(name)
		if v[1] == 'set':
			vals[name] = 1
		elif v[1] == 'clear':
			vals[name] = None
		else:
			cur = vals.get(name) or 0
			x = float(v[2]) if v[2] is not None else 0
			vals[name] = {'=': x, '+=': cur + x, '-=': cur - x, '++': cur + 1, '--': cur - 1,
				'<?=': min(cur, x), '>?=': max(cur, x), '*=': cur * x, '/=': cur / x if x else cur}[v[1]]
	return [(k, vals[k]) for k in order if vals[k] is not None]


def emit(data, out):
	c = Campaign(data)
	end = c.date(c.end)
	L = []
	W = L.append
	W('# Diplomacy: the "Free Worlds Veteran" start. GENERATED by mods/diplomacy/tools/fw-veteran/emit.py')
	W('# from the game\'s data (data/human/free worlds *.txt and campaign events.txt): edit path.py and run it')
	W('# again rather than editing this file. tools/fw-veteran/check.py checks it against the game data.')
	W('#')
	W('# A new pilot who has just finished the Free Worlds campaign, with the galaxy, conditions, reputations')
	W('# and licenses a real finish leaves, so that Diplomacy (which waits for "free worlds plot completed")')
	W('# offers itself on the first landing. The path is the Reconciliation ending on the honorable branches')
	W('# (see path.py). It is placed on a nominal timeline from 18 Sep 3014 and ends on'
		f' {end.day} {end.month} {end.year}.')
	W('# The intro conversation applies each of its events and reputation changes in order; the events still')
	W('# pending at the end are scheduled at their remaining offsets, as in a real game.')
	W('')
	W('start "diplomacy: free worlds veteran"')
	W('\tname "Free Worlds Veteran (Diplomacy)"')
	W("\tdescription `You flew for the Free Worlds through the whole war, from the battle over Sabik to the Pug"
		" retreat and the Syndicate extremists at Algenib. Parliament has recognized the Free Worlds, pardoned"
		" the Council and given you a commendation and five million credits. The Council is dissolved, but the"
		" Free Worlds still pay you a salary, and the Republic, the Free Worlds and the Syndicate are already"
		" eyeing each other's borders...`")
	W("\tdescription `\tThis start skips the Free Worlds campaign and begins the day it ends (the Reconciliation"
		" ending), with the galaxy, standing, licenses and salary a real finish leaves. It is meant for the"
		" Diplomacy plugin, which offers itself when you land.`")
	W('\tthumbnail "scene/earth"')
	W(f'\tdate {end.day} {end.month} {end.year}')
	W('\tsystem "Sol"')
	W('\tplanet "Earth"')
	W('\tconversation "diplomacy: free worlds veteran intro"')
	W('\taccount')
	W(f'\t\tcredits {CREDITS}')
	W('\t\tscore 400')
	W(f'\tship "Osprey (Free Worlds Veteran)" {q(SHIP_NAME)}')
	W('\tset "license: Pilot\'s"')
	W('\tset "species: human"')
	W('\tset "human space start"')
	W('\tset "start: diplomacy free worlds veteran"')
	W('\t# The mod applies the Luna yard itself unless this is set (the intro applies it).')
	W('\tset "diplomacy: luna yard"')
	W('\t# The conditions the campaign leaves set, with their final values.')
	for k, v in final_conditions(c):
		if v == 1 and k not in ('karma', 'assisted free worlds') and not k.startswith('salary: '):
			W(f'\tset {q(k)}')
		else:
			W(f'\t{q(k)} = {int(v)}')
	W('\t# Every mission of the path, as it ends (done, declined or failed), so that none is offered again.')
	seen = set()
	for rel, name, day in c.offered:
		W(f'\tset {q(name + ": offered")}')
		W(f'\tset {q(name + ": " + c.status(rel, name))}')
		seen.add(name)
	W('\t# Missions that fire on their own along the way.')
	extra = list(P.EXTRA) + [(t, 'failed', 'an invisible trigger; its events are applied below') for r, t, w in P.TRIGGERS]
	for name, st, why in extra:
		if name in seen:
			continue
		W(f'\t# {why}')
		W(f'\tset {q(name + ": offered")}')
		W(f'\tset {q(name + ": " + st)}')
	W('')
	W('# The stock Osprey (Tarazed built it, and Tarazed joins the Free Worlds), with the Jump Drive that')
	W('# FW Pug 2C: Hyperdrive installs in place of its Hyperdrive.')
	W('ship "Osprey" "Osprey (Free Worlds Veteran)"')
	W('\toutfits')
	for o in OSPREY:
		W('\t\t' + o)
	W('')
	W('conversation "diplomacy: free worlds veteran intro"')
	# The logbook entries every human pilot gets: the factions from the default intro, and Remembrance Day.
	starts = parse(os.path.join(data, 'starts.txt'))
	intro = [n for n in starts.children if n.tokens[:2] == ['conversation', 'default intro']][0]
	early = [g for a in intro.children if a.tokens[0] == 'action' for g in a.children if g.tokens[0] == 'log' and len(g.tokens) >= 3]
	remembrance = c.missions(P.CE)['remembrance day']
	early += [g for g in walk(remembrance) if g.tokens[0] == 'log' and len(g.tokens) >= 3]
	W('\t# The logbook entries of the default intro and of Remembrance Day, which every pilot of the era has.')
	for g in early:
		W('\taction')
		W(f'\t\tlog {q(g.tokens[1])} {q(g.tokens[2])}')
		for text in g.tokens[3:] + [x.tokens[0] for x in g.children]:
			W(f'\t\t\t`{text}`')
	W('\t# The campaign\'s events and reputation changes, in the order the path applies them, one action each')
	W('\t# (an action applies its own events in no fixed order). "0" applies an event at once.')
	for d, s, k, v, src in c.timeline:
		if k == 'event':
			date = c.date(d)
			W('\taction')
			W(f'\t\t# {date.day} {date.month} {date.year}: {src}')
			W(f'\t\tevent {q(v)} {max(0, d - c.end)}')
		elif k == 'cond' and v[0].startswith('reputation: '):
			W('\taction')
			W(f'\t\t# {src}')
			W(f'\t\t{q(v[0])} {v[1]} {v[2]}')
		elif k == 'log' and len(v) >= 3:
			W('\taction')
			W(f'\t\t# {src}')
			W(f'\t\tlog {q(v[0])} {q(v[1])}')
			for text in v[2:]:
				W(f'\t\t\t`{text}`')
	W('\t# Diplomacy\'s own: the Navy Advanced shipyard on Luna (data/diplomacy.txt), since the campaign')
	W('\t# wrecked Geminus, the only other world that sells it, and Diplomacy lets Geminus change hands.')
	W('\taction')
	W(f'\t\tevent {q(LUNA_EVENT)} 0')
	W('\t# The campaign\'s reward that is not part of the ship: FW Syndicate Extremists 1B gives the cloaking')
	W('\t# device, which does not fit in the Osprey\'s outfit space, so it goes to the cargo hold.')
	W('\taction')
	W('\t\toutfit "Cloaking Device"')
	W('\t\tlog `Flew for the Free Worlds through the whole war, from Sabik to the Pug retreat and the battle at'
		' Algenib. Parliament has recognized the Free Worlds, pardoned the Council and given me a commendation.'
		' Humanity is at peace, for now.`')
	W('\tscene "scene/earth"')
	W("\t`On Earth, you return to something of a hero's welcome. Parliament has pardoned the Council, recognized"
		" the Free Worlds and awarded you an official commendation, with five million credits \"to cover any of"
		" your expenses from fighting the aliens.\" The Council itself has been dissolved, but the Free Worlds"
		" have kept you on a reduced salary in honor of your service.`")
	W("\t`\tThe war is over. The Pug have fled beyond their wormhole, the Navy is pulling out of the south, and"
		" Tarazed and Bloodsea fly the Free Worlds flag. Your Osprey waits in the spaceport, a jump drive where"
		" its hyperdrive used to be and the Syndicate extremists' cloaking device in its hold.`")
	W('\t`\tThe commendation still needs your signature. You sign it:`')
	W('\tname')
	W("\t`\tThe peace between the Republic, the Free Worlds and the Syndicate is new, and borders drawn in a"
		" war may not stay where they are for long. What you do next is up to you...`")
	with open(out, 'w', encoding='utf-8') as f:
		f.write('\n'.join(L) + '\n')
	return c


if __name__ == '__main__':
	if len(sys.argv) < 2:
		sys.exit(__doc__)
	out = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
	c = emit(sys.argv[1], out)
	print(f'wrote {out}: the campaign ends on {c.date(c.end)}')
