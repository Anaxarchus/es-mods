// Checks the carve-up of human space (tools/regions/regions.mjs) against the
// game's map, and writes what is made from it:
//   src/Regions.dados              the table, for the mod
//   data/diplomacy factions.txt    a government and two fleets per rebel faction
//                                  (the parent's "Small"/"Large" fleets, copied
//                                  from the game's data, under the rebels' flag)
//   README.md                      the table, between <!-- regions --> markers
//
//   node mods/diplomacy/tools/regions/build.mjs [<endless-sky>/data]    check and write
//   node mods/diplomacy/tools/regions/build.mjs --check                 check only (test/regions.test.mjs)
//
// The map is test/galaxy.json (the Free Worlds Veteran galaxy, from
// tools/make-galaxy.mjs). The fleets need the game's data folder; without it the
// existing data/diplomacy factions.txt is kept. Checks: every human system
// (Republic, Free Worlds, Syndicate, Pirate or Independent in that galaxy) is in
// exactly one minor; every minor is contiguous over lanes inside it (pirate
// enclaves excepted); each major has exactly one core, which holds its capital;
// every non-core, non-pirate minor names its rebels and their colour.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MINORS, CAPITALS } from './regions.mjs';
import { tree } from '../../test/galaxy.mjs';

const MOD = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MAJORS = ['Republic', 'Free Worlds', 'Syndicate'];
const SIDE = { 'Republic': 1, 'Free Worlds': 2, 'Syndicate': 3, 'Pirate': 4 };
const SWIZZLE = { 'Republic': 0, 'Free Worlds': 2, 'Syndicate': 4 };
const HUMAN = new Set(['Republic', 'Free Worlds', 'Syndicate', 'Pirate', 'Independent']);

export function check(galaxyJson = JSON.parse(readFileSync(join(MOD, 'test', 'galaxy.json'), 'utf8'))) {
	const problems = [];
	const sys = galaxyJson.systems;
	const where = new Map();
	for (const m of MINORS) {
		if (!SIDE[m.parent]) problems.push(`${m.name}: unknown parent ${m.parent}`);
		if (!m.core && m.parent !== 'Pirate' && (!m.rebels || !m.colour)) problems.push(`${m.name}: names no rebels or colour`);
		if (m.core && m.rebels) problems.push(`${m.name}: a core never rebels`);
		if (!/^[A-Za-z' ]+$/.test(m.short)) problems.push(`${m.name}: short name "${m.short}" must be letters and spaces`);
		for (const s of m.systems) {
			if (!sys[s]) problems.push(`${m.name}: ${s} is not in the map`);
			if (where.has(s)) problems.push(`${s} is in both ${where.get(s)} and ${m.name}`);
			where.set(s, m.name);
		}
		// Contiguous over lanes inside the minor, enclaves aside.
		const inside = new Set(m.systems.filter(s => !(m.enclaves || []).includes(s)));
		const first = [...inside][0];
		const seen = new Set([first]);
		const queue = [first];
		while (queue.length) for (const l of (sys[queue.pop()]?.links || [])) if (inside.has(l) && !seen.has(l)) { seen.add(l); queue.push(l); }
		const cut = [...inside].filter(s => !seen.has(s));
		if (cut.length) problems.push(`${m.name} is not contiguous: ${cut.join(', ')} cut off from ${first}`);
	}
	for (const [name, s] of Object.entries(sys))
		if (HUMAN.has(s.government) && !where.has(name)) problems.push(`${name} (${s.government}) is in no minor`);
	for (const major of MAJORS) {
		const cores = MINORS.filter(m => m.core && m.parent === major);
		if (cores.length !== 1) problems.push(`${major} has ${cores.length} cores`);
		else if (!cores[0].systems.includes(CAPITALS[major])) problems.push(`${major}'s core ${cores[0].name} lacks its capital ${CAPITALS[major]}`);
		if (sys[CAPITALS[major]]?.government !== major) problems.push(`${CAPITALS[major]} is not ${major}'s in the map`);
	}
	return problems;
}

const q = s => '"' + s.replace(/"/g, '\\"') + '"';

function dados() {
	const L = [];
	L.push('class Regions', '');
	L.push('// GENERATED by tools/regions/build.mjs from tools/regions/regions.mjs; do not', '// edit. The minor factions of human space (README.md, "Factions and minors"):', '// minor k is names[k], held by default by parents[k] (1 the Republic, 2 the', '// Free Worlds, 3 the Syndicate, 4 the pirates). A core (cores[k]) is a major\'s', '// home region, with its capital; it never rebels. rebels[k] is the government', '// minor k forms if it secedes ("" for a core or pirate holding), defined with', '// its fleets in data/diplomacy factions.txt.', '');
	L.push('[]string names = [' + MINORS.map(m => q(m.name)).join(', ') + ']');
	L.push('[]string shorts = [' + MINORS.map(m => q(m.short)).join(', ') + ']');
	L.push('[]int parents = [' + MINORS.map(m => SIDE[m.parent]).join(', ') + ']');
	L.push('[]bool cores = [' + MINORS.map(m => m.core ? 'true' : 'false').join(', ') + ']');
	L.push('[]string rebels = [' + MINORS.map(m => q(m.rebels || '')).join(', ') + ']');
	for (const [k, c] of [['red', 0], ['green', 1], ['blue', 2]])
		L.push('[]float ' + k + ' = [' + MINORS.map(m => (m.colour ? m.colour[c] : 0.5).toFixed(2)).join(', ') + ']');
	L.push('[][]string systems = [');
	for (const m of MINORS) L.push('    [' + m.systems.map(q).join(', ') + '],');
	L.push(']');
	L.push('[]string capitals = ["", ' + MAJORS.map(m => q(CAPITALS[m])).join(', ') + ']');
	L.push('', 'int count():', '    return names.len()', '');
	return L.join('\n') + '\n';
}

// src/Trade.dados: the base prices of the commodities damage touches (Tuning.
// damaged_goods), for each human system with a market, from the galaxy (the
// game's data with the Veteran start's events). The mod uses it on a game
// without mod API 10's trade_base_price.
export const DAMAGED_GOODS = ['Food', 'Medical', 'Clothing'];
function tradeDados(galaxyJson) {
	const L = ['class Trade', '', '// GENERATED by tools/regions/build.mjs from test/galaxy.json (the game\'s map', '// with the Free Worlds Veteran start\'s events); do not edit. Base prices, for a', '// game without mod API 10\'s trade_base_price: "system|commodity" -> price.', ''];
	const entries = [];
	for (const m of MINORS) for (const s of m.systems) {
		const t = galaxyJson.systems[s]?.trade || {};
		for (const g of DAMAGED_GOODS) if (t[g] > 0) entries.push(q(s + '|' + g + '|' + t[g]));
	}
	L.push('[]string rows = [');
	for (let k = 0; k < entries.length; k += 6) L.push('    ' + entries.slice(k, k + 6).join(', ') + ',');
	L.push(']', '{string: int} prices = {}', '', '// The price, or 0 when the system has no market for it.', 'int base(string system, string commodity):');
	L.push('    if prices.len() == 0:', '        for r in rows:', '            []string f = r.split("|")', '            prices[f[0] + "|" + f[1]] = f[2].to_int()');
	L.push('    return prices.get(system + "|" + commodity, 0)', '');
	return L.join('\n') + '\n';
}

// The block of a top-level node in a data file, as its lines.
function block(lines, header) {
	const i = lines.findIndex(l => l.trimEnd() === header);
	if (i < 0) return null;
	let j = i + 1;
	while (j < lines.length && (lines[j].startsWith('\t') || lines[j].trim() === '' || lines[j].startsWith('#'))) j++;
	while (j > i + 1 && lines[j - 1].trim() === '') j--;
	return lines.slice(i, j);
}

function factionsData(data) {
	const fleets = readFileSync(join(data, 'human', 'fleets.txt'), 'utf8').split('\n');
	const L = ['# GENERATED by tools/regions/build.mjs from tools/regions/regions.mjs and the game\'s', '# data/human/fleets.txt; do not edit. For each minor that can secede, the government', '# its rebels fly under and two fleets (its parent\'s "Small" and "Large" fleets, the', '# same ships under the rebels\' flag). The mod sets their attitudes as wars start', '# and end; until a minor rebels nothing uses them.', ''];
	for (const m of MINORS) {
		if (!m.rebels) continue;
		L.push(`government ${q(m.rebels)}`, `\t"display name" ${q(m.rebels)}`, `\tswizzle ${SWIZZLE[m.parent]}`, `\tcolor ${m.colour.map(x => x.toFixed(2)).join(' ')}`, '\t"player reputation" 1', '\t"attitude toward"', '\t\t"Merchant" .3', '\t\t"Militia" .3', '\t\t"Pirate" -.4', '');
		for (const size of ['Small', 'Large']) {
			const b = block(fleets, `fleet "${size} ${m.parent}"`);
			if (!b) throw new Error(`fleet "${size} ${m.parent}" is not in ${data}/human/fleets.txt`);
			L.push(`fleet ${q(size + ' ' + m.rebels)}`);
			for (const line of b.slice(1)) L.push(/^\tgovernment /.test(line) ? `\tgovernment ${q(m.rebels)}` : line);
			L.push('');
		}
	}
	return L.join('\n');
}

function readmeTable(galaxyJson) {
	const sys = galaxyJson.systems;
	const L = ['| Minor | Default parent | Systems | Key systems | Rebels |', '|---|---|---|---|---|'];
	for (const m of MINORS) {
		const held = {};
		for (const s of m.systems) held[sys[s].government] = (held[sys[s].government] || 0) + 1;
		const split = Object.entries(held).map(([g, n]) => `${g} ${n}`).join(', ');
		const kind = m.core ? `**${m.parent} (core)**` : m.parent === 'Pirate' ? 'pirates' : m.parent;
		const capital = m.core ? `capital **${CAPITALS[m.parent]}**; ` : '';
		L.push(`| ${m.name[0].toUpperCase() + m.name.slice(1)} | ${kind} | ${m.systems.length} (${split}) | ${capital}${m.systems.join(', ')} | ${m.rebels || '—'} |`);
	}
	return L.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const galaxyJson = JSON.parse(readFileSync(join(MOD, 'test', 'galaxy.json'), 'utf8'));
	const problems = check(galaxyJson);
	for (const p of problems) console.error('FAIL ' + p);
	if (problems.length) process.exit(1);
	console.log(`ok   ${MINORS.length} minors cover human space; each contiguous; each major's core holds its capital`);
	if (process.argv[2] === '--check') process.exit(0);
	writeFileSync(join(MOD, 'src', 'Regions.dados'), dados());
	writeFileSync(join(MOD, 'src', 'Trade.dados'), tradeDados(galaxyJson));
	console.log('wrote src/Regions.dados and src/Trade.dados');
	const data = process.argv[2] || process.env.ES_DATA;
	if (data && existsSync(join(data, 'human', 'fleets.txt'))) {
		writeFileSync(join(MOD, 'data', 'diplomacy factions.txt'), factionsData(data));
		console.log('wrote data/diplomacy factions.txt');
	} else console.log('no game data folder given: data/diplomacy factions.txt kept');
	const readme = join(MOD, 'README.md');
	const text = readFileSync(readme, 'utf8');
	const a = text.indexOf('<!-- regions -->'), b = text.indexOf('<!-- /regions -->');
	if (a >= 0 && b > a) {
		writeFileSync(readme, text.slice(0, a) + '<!-- regions -->\n' + readmeTable(galaxyJson) + '\n' + text.slice(b));
		console.log('wrote the table in README.md');
	}
}

export { dados, readmeTable, tradeDados };
