// Writes data/racing.txt: spaceport news near each circuit in its race week
// (shown while the condition "racing: news <system>" is at least the day,
// set by the mod; racing.dados news_conditions). Run: node tools/make-news.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(HERE, "../src/Names.dados"), "utf8");
const list = (name) => JSON.parse(src.match(new RegExp(`\\]?${name} = (\\[.*\\])`))[1]);
const systems = list("circuit_systems");
const titles = list("circuit_titles");
const lines = [
	"# GENERATED by tools/make-news.mjs; do not edit by hand.",
	"# The Racing League keeps its leagues with the pilot (mod API 6 storage). This",
	"# file holds only spaceport news near each circuit in its race week.",
	"",
	'phrase "racing: speakers"',
	"\tword",
	'\t\t"Racing fan"',
	'\t\t"Bookmaker"',
	'\t\t"Pit mechanic"',
	'\t\t"Holovid commentator"',
	"",
];
const said = [
	(t) => `The ${t} is this week. Every hotel near the course is booked solid.`,
	(t) => `Odds on the ${t} are all over the place. The smart money says watch the pit stops.`,
	(t) => `They've strung marker buoys all along the ${t}. You can see the practice runs from orbit.`,
];
systems.forEach((s, k) => {
	lines.push(`news "racing: ${s}"`, "\tlocation", `\t\tnear "${s}" 1`, "\tname", "\t\tphrase", '\t\t\t"racing: speakers"', "\tmessage", "\t\tword");
	for (const f of said) lines.push(`\t\t\t\`${f(titles[k])}\``);
	lines.push("\tto show", `\t\t"racing: news ${s}" >= "days since epoch"`, "");
});
writeFileSync(join(HERE, "../data/racing.txt"), lines.join("\n"));
console.log(`wrote data/racing.txt (${systems.length} circuits)`);
