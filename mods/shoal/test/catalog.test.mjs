// The Breakers' Yard's catalogue of stock outfits (src/Catalog.dados), made
// from the game's data. It is the FALLBACK for games before mod API 12: with
// API 12 the yard lists what is installed (ship_outfit_kinds/ship_outfit_at)
// and reads weapon stats (outfit_weapon_attribute), and never uses it. An
// API 11 game can neither list a ship's installed outfits nor read a weapon's
// stats (its damage lives in the weapon block, which outfit_attribute does
// not reach), so there the yard looks for these names on the player's ships
// and takes weapon stats from here.
//
//   node mods/shoal/test/catalog.test.mjs --write [<endless-sky>/data]
//       writes src/Catalog.dados
//   node --test mods/shoal/test/catalog.test.mjs
//       checks that src/Catalog.dados is what the game's data makes (skipped
//       when the game's data is not found: $ES_GAME_DATA, or ../argosy/data
//       beside the SDK's parent, or /root/fork/argosy/data)
//
// What is listed: every outfit in the categories that hold upgradable kinds
// (Guns, Turrets, Secondary Weapons, Systems, Power, Engines) that has one of
// the attributes the yard classifies by. That is only a shortlist: the mod
// classifies each outfit again at run time from the game's own attributes.
// A weapon is listed only when its own weapon block deals damage or stops
// missiles (a weapon whose damage is all in submunitions cannot be scaled).
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "../src/Catalog.dados");
const CATEGORIES = new Set(["Guns", "Turrets", "Secondary Weapons", "Systems", "Power", "Engines"]);
// The attributes the yard's kinds are recognised by (Tuning.kind_test).
const KIND_ATTRIBUTES = ["shield generation", "energy generation", "energy capacity", "cooling", "active cooling", "heat dissipation", "thrust", "turn", "afterburner thrust", "hull repair rate", "hull"];
// Weapon stats the yard scales: damage of every type and anti-missile
// strength (the headline), and the firing costs.
const COSTS = ["firing energy", "firing heat", "firing fuel"];
const isHeadline = (k) => k.endsWith(" damage") || k === "anti-missile";

function files(dir) {
	return readdirSync(dir).flatMap((f) => {
		const p = join(dir, f);
		return statSync(p).isDirectory() ? files(p) : p.endsWith(".txt") ? [p] : [];
	}).sort();
}

function tokens(line) {
	const out = [];
	const re = /"([^"]*)"|`([^`]*)`|(\S+)/g;
	let m;
	while ((m = re.exec(line))) {
		if (m[3] !== undefined && m[3].startsWith("#")) break;
		out.push(m[1] ?? m[2] ?? m[3]);
	}
	return out;
}

// Every `outfit "<name>"` node in the data: its category, its numeric
// attributes, and its weapon block's numeric keys (last definition wins).
export function readOutfits(root) {
	const outfits = new Map();
	for (const file of files(root)) {
		let cur = null;
		let inWeapon = false;
		for (const raw of readFileSync(file, "utf8").split("\n")) {
			if (!raw.trim() || raw.trim().startsWith("#")) continue;
			const indent = raw.match(/^\t*/)[0].length;
			const t = tokens(raw.slice(indent));
			if (!t.length) continue;
			if (indent === 0) {
				inWeapon = false;
				cur = null;
				if (t[0] === "outfit" && t.length === 2) {
					cur = { category: "", attributes: {}, weapon: null };
					outfits.set(t[1], cur);
				}
				continue;
			}
			if (!cur) continue;
			if (indent === 1) {
				inWeapon = t[0] === "weapon";
				if (inWeapon) cur.weapon ??= {};
				else if (t[0] === "category" && t.length >= 2) cur.category = t[1];
				else if (t.length === 2 && Number.isFinite(Number(t[1]))) cur.attributes[t[0]] = Number(t[1]);
				continue;
			}
			if (indent === 2 && inWeapon && t.length === 2 && Number.isFinite(Number(t[1]))) cur.weapon[t[0]] = Number(t[1]);
		}
	}
	return outfits;
}

export function catalog(root) {
	const names = [];
	const stats = [];
	for (const [name, o] of [...readOutfits(root)].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
		if (!CATEGORIES.has(o.category)) continue;
		if (o.weapon) {
			const keys = Object.keys(o.weapon).filter((k) => (isHeadline(k) && o.weapon[k] > 0) || (COSTS.includes(k) && o.weapon[k] !== 0)).sort();
			if (!keys.some(isHeadline)) continue;
			names.push(name);
			stats.push(keys.map((k) => `${k}=${o.weapon[k]}`).join(";"));
		} else if (KIND_ATTRIBUTES.some((a) => (o.attributes[a] ?? 0) > 0)) {
			names.push(name);
			stats.push("");
		}
	}
	return { names, stats };
}

export function render({ names, stats }) {
	return [
		"class Catalog",
		"",
		"// GENERATED by test/catalog.test.mjs from the game's data; do not edit by hand.",
		"//",
		"// FALLBACK ONLY: used on games before mod API 12. With API 12 the yard lists",
		"// every installed outfit and reads weapon stats from the game, and ignores this.",
		"// Run: node mods/shoal/test/catalog.test.mjs --write <endless-sky>/data",
		"//",
		"// The stock outfits the Breakers' Yard looks for on the player's ships (mod",
		"// API 11 cannot list a ship's outfits), and each weapon's stats as its data",
		"// writes them, \"key=value\" joined by \";\" (\"\" for an outfit that is not a",
		"// weapon): API 11 cannot read a weapon block. The yard classifies every",
		"// outfit again from the game's own attributes; this is only the shortlist.",
		"",
		`[]string names = ${JSON.stringify(names)}`,
		`[]string stats = ${JSON.stringify(stats)}`,
		"",
	].join("\n");
}

function gameData() {
	const candidates = [process.env.ES_GAME_DATA, resolve(HERE, "../../../../argosy/data"), "/root/fork/argosy/data"];
	return candidates.find((d) => d && existsSync(join(d, "human")));
}

if (process.argv.includes("--write")) {
	const at = process.argv.indexOf("--write");
	const root = process.argv[at + 1] ?? gameData();
	if (!root) throw new Error("usage: catalog.test.mjs --write <endless-sky>/data");
	const c = catalog(root);
	writeFileSync(OUT, render(c));
	console.log(`wrote ${OUT}: ${c.names.length} outfits, ${c.stats.filter((s) => s).length} of them weapons`);
} else {
	const root = gameData();
	test("src/Catalog.dados is what the game's data makes", { skip: !root && "no game data" }, () => {
		assert.equal(readFileSync(OUT, "utf8"), render(catalog(root)), "run: node mods/shoal/test/catalog.test.mjs --write");
	});
	test("the catalogue lists stock outfits by kind, with weapon stats", { skip: !root && "no game data" }, () => {
		const { names, stats } = catalog(root);
		const at = (n) => names.indexOf(n);
		assert.ok(at("D14-RN Shield Generator") >= 0 && stats[at("D14-RN Shield Generator")] === "");
		assert.match(stats[at("Heavy Laser")], /hull damage=\d/);
		assert.match(stats[at("Anti-Missile Turret")], /anti-missile=\d/);
		assert.equal(at("Hyperdrive"), -1, "no kind the yard upgrades");
		assert.equal(at("Sidewinder Missile"), -1, "ammunition is not listed");
	});
}
