# Adds the Glass-Edge Cutlass roll (DESIGN.md section 19) to every drowned
# hull pool, rewriting the plugin's data in place. Run from anywhere:
#	ES_DATA=<es>/data python3 tools/h2h/h2h.py
#
# Per drowned WARSHIP (Osprey, Falcon, Leviathan, Bactrian) in a spawn, an
# independent roll: none (weight NONE) or one of COUNTS cutlasses (weight 1
# each), carried in the ship's cargo hold. Each fleet variant is expanded into
# every combination of its warships' rolls, with weight
#	original weight x 40^(K - k) x product of the rolls' weights
# (k warships in the variant, K the most in any variant of the pool), so each
# original variant keeps its share and the exotic distribution is unchanged.
# The generated ship variants ("<ship> [Cutlass n]") go to
# "data/shoal cutlass ships.txt", which is rewritten whole.
#
# Idempotent: existing "[Cutlass n]" entries are collapsed back to their
# original variant (summed, then divided by the gcd) before expanding again.
import os, re, sys
from math import gcd
from functools import reduce
from itertools import product
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ambushers"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from es import *

from h2h_common import *

DATA = PLUGIN_DATA
FLEET_FILE = os.path.join(DATA, "shoal fleets.txt")
MISSION_FILE = os.path.join(DATA, "shoal missions.txt")
SHIP_FILE = os.path.join(DATA, "shoal ships.txt")
OUT_FILE = os.path.join(DATA, "shoal cutlass ships.txt")

init_blocks(SHIP_FILE)

def expand(vs, pool):
	"""Collapse existing rolled entries, then expand every ship's rolls (the
	pool's core roll, and the cutlass roll on warships). Each original variant
	keeps its share: its states' weights sum to D (the product of its ships'
	roll totals), so it is scaled by L / D with L the lcm of every D."""
	base = {}; order = []
	for w, ships in vs:
		key = tuple(strip(s) for s in ships)
		if key not in base: base[key] = 0; order.append(key)
		base[key] += w
	g = reduce(gcd, base.values())
	def total(key):
		t = 1
		for s in key: t *= sum(w for _, w in ship_states(s, pool))
		return t
	L = reduce(lambda a, b: a * b // gcd(a, b), (total(k) for k in order))
	out = []
	for key in order:
		w0 = base[key] // g * (L // total(key))
		for combo in product(*(ship_states(s, pool) for s in key)):
			w = w0; ships = list(key)
			for i, ((k, c), sw) in enumerate(combo):
				w *= sw
				ships[i] = variant_name(key[i], c, k)
			out.append((w, ships))
	g = reduce(gcd, [w for w, _ in out])
	return [(w // g, ships) for w, ships in out]

used = set()
def rewrite_fleets(path):
	lines = open(path, encoding="utf8").read().split("\n")
	i = 0; done = []
	while i < len(lines):
		t = tok(lines[i]) if lines[i] and not lines[i][0].isspace() else None
		if t and t[0] == "fleet" and len(t) > 1 and t[1] in FLEETS:
			j = i + 1
			while j < len(lines) and (not lines[j] or lines[j][0].isspace()): j += 1
			a, b, vs = parse_variants(lines, i + 1, j, 1)
			nv = expand(vs, t[1])
			for _, ships in nv: used.update(ships)
			R = render(nv, 1)
			lines[a:b] = R
			done.append(t[1])
			i = a + len(R)
			continue
		i += 1
	assert sorted(done) == sorted(FLEETS), done
	open(path, "w", encoding="utf8").write("\n".join(lines))

def rewrite_missions(path):
	lines = open(path, encoding="utf8").read().split("\n")
	i = 0; done = []
	mission = None
	while i < len(lines):
		line = lines[i]
		if line and not line[0].isspace():
			t = tok(line); mission = t[1] if t and t[0] == "mission" and len(t) > 1 else None
		elif mission in MISSIONS and line == "\t\tfleet":
			j = i + 1
			while j < len(lines) and (not lines[j].strip() or len(lines[j]) - len(lines[j].lstrip("\t")) > 2): j += 1
			a, b, vs = parse_variants(lines, i + 1, j, 3)
			if all(strip(s).startswith("Drowned") for _, ss in vs for s in ss):
				nv = expand(vs, "mission " + mission)
				for _, ships in nv: used.update(ships)
				lines[a:b] = render(nv, 3)
				done.append(mission)
		i += 1
	assert sorted(set(done)) == sorted(MISSIONS), done
	open(path, "w", encoding="utf8").write("\n".join(lines))

rewrite_fleets(FLEET_FILE)
rewrite_missions(MISSION_FILE)

HEADER = """# Generated by tools/h2h/h2h.py: do not edit by hand (DESIGN.md sections 19, 21).
#
# Rolled copies of the drowned ships of every drowned pool, with items in the
# hold: "[Cutlass n]" Glass-Edge Cutlasses on warships (Osprey, Falcon,
# Leviathan, Bactrian; an independent 20%% roll per warship in every drowned
# pool, the counts %s at equal weight), "[Core c]" Warden Cores (since
# v0.3.5: an independent roll per ship in the derelict wreck fleets, see
# CORE_ROLLS in h2h_common.py), or both. Each copy is its original variant
# (same outfits, still uncapturable) plus the cargo; a variant with no
# outfits of its own inherits the hull's. The cutlass is "unplunderable" like
# stock hand-to-hand gear, so both ride as cargo, which boarding can always
# take.
""" % ", ".join(map(str, COUNTS))

out = [HEADER]
gen = sorted((s for s in used if SUFFIX.search(s)), key=lambda s: (hull(s), strip(s), rolled(s)))
for v in gen:
	s = strip(v); k, c = rolled(v)
	t, body = BLOCKS[s]
	L = ['ship "%s" "%s"' % (t[1], v)]
	if len(t) == 2:
		# A hull used as it is: the variant inherits its outfits.
		L.append("\tuncapturable")
	else:
		if any(l.strip().startswith("cargo") and len(l) - len(l.lstrip("\t")) == 1 for l in body):
			raise Exception("%s already has cargo" % s)
		L += body
	L += ["\tcargo", "\t\toutfits"]
	if k: L.append('\t\t\t"%s" %d' % (CORE, k))
	if c: L.append('\t\t\t"%s" %d' % (OUTFIT, c))
	out.append("\n".join(L) + "\n")
open(OUT_FILE, "w", encoding="utf8").write("\n".join(out))
print("%d rolled variants (%d with cutlasses, %d with cores) of %d ships" % (len(gen),
	sum(1 for v in gen if rolled(v)[1]), sum(1 for v in gen if rolled(v)[0]), len({strip(v) for v in gen})))
