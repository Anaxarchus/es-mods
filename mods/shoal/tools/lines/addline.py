# Adds one exotic line to the hand-built drowned pools: "Shoal Wrecks"
# ("(Worn, X)"), "Shoal Glass Wrecks" and "Shoal Rich Wrecks" ("(Rich, X)",
# "(Rich, X II)"), "Shoal Deep Wreck" ("(Deep, X)", "(Deep, X II)") and the
# salvage lead "Shoal: Lead Warship" ("(Lead, X)", "(Lead, X II)"), keeping
# every pool's overall exotic rates and spreading the exotics evenly over the
# lines (DESIGN.md sections 15, 19, 21). The ambushers and the hunter come from
# ../ambushers/gen.py instead.
#	ES_DATA=<es>/data python3 tools/lines/addline.py
#	then: python3 tools/h2h/h2h.py (the cutlass roll), tools/ambushers/cap.py
#
# How (on each pool, with its cutlass expansion collapsed first):
# * every entry that carries a TEMPLATE-line ship ("(Kind, Driftnet)" or
#   "(Kind, Driftnet II)") is copied with that ship replaced by the new line's
#   ship of the same kind and mark, at the same weight;
# * then, with N lines before, every entry carrying an exotic (the new ones
#   included) is weighted x N and every plain entry x (N + 1). Each line's
#   exotic weight is then N x w against plain (N + 1) x P, so the exotic share
#   (N + 1) N w / ((N + 1) P + (N + 1) N w) = N w / (P + N w) is unchanged,
#   and each line, the new one too, gets 1 / (N + 1) of it.
# The new ship variants are copies of a DONOR line's variants on the new
# line's hull (same kind and mark: the same outfits and loot), with the
# donor's exotic swapped for the new one plus EXTRA (its ammunition); they are
# written into "shoal ships.txt" between the marker comments below (replaced
# on a rerun). The pools are written collapsed (no "[Cutlass n]" entries), so
# run ../h2h/h2h.py afterwards. A pool that already has the new line is left
# alone, so the script is safe to rerun.
import os, re, sys
from math import gcd
from functools import reduce
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "ambushers"))
sys.path.insert(0, os.path.join(HERE, "..", "h2h"))
from es import tok, PLUGIN_DATA
from h2h_common import strip, parse_variants, render

# The line to add (v0.3.5: the Lamprey Launcher, line 14).
NEW = "Lamprey"                        # label in variant names
NEW_OUTFIT = "Lamprey Launcher"        # "<outfit> Mk I" / "Mk II"
EXTRA = [("Glass Lamprey", 10)]        # loaded with each launcher
LINES_BEFORE = 13
TEMPLATE = "Driftnet"                  # an existing line whose pool entries are copied
# Hull of the new line per kind, and the donor line on that hull whose variant
# is copied (its exotic, "<DONOR_OUTFIT> Mk I/II", is swapped for the new one).
HULL = {"Worn": "Bulk Freighter", "Rich": "Bulk Freighter", "Lead": "Bulk Freighter", "Deep": "Bactrian"}
DONOR, DONOR_OUTFIT = "Coral", "Coral Plating"

DATA = PLUGIN_DATA
SHIP_FILE = os.path.join(DATA, "shoal ships.txt")
FLEET_FILE = os.path.join(DATA, "shoal fleets.txt")
MISSION_FILE = os.path.join(DATA, "shoal missions.txt")
# Since 0.5.0 the warship lead's wrecks are a fleet ("Shoal Lead Warship Wreck"),
# no longer inline in the mission, and the Abyss wreck (tools/deep/abyss.py)
# copies the deep wrecks: run abyss.py again after adding a line.
FLEETS = ["Shoal Wrecks", "Shoal Glass Wrecks", "Shoal Rich Wrecks", "Shoal Deep Wreck", "Shoal Lead Warship Wreck"]
MISSIONS = []
BEGIN = "# BEGIN %s line (generated by tools/lines/addline.py; do not edit by hand)" % NEW
END = "# END %s line" % NEW
KIND = re.compile(r"^Drowned (.+) \((Worn|Rich|Deep|Lead), ([A-Za-z]+)( II)?\)$")

def new_ship(kind, mk2): return "Drowned %s (%s, %s%s)" % (HULL[kind], kind, NEW, " II" if mk2 else "")

def is_exotic(ship): return bool(KIND.match(strip(ship)))

def convert(vs):
	"""vs: [(weight, [ships])] with cutlass entries. Returns the collapsed,
	extended, reweighted variants, or None if the pool has the line already."""
	base = {}; order = []
	for w, ships in vs:
		key = tuple(strip(s) for s in ships)
		if key not in base: base[key] = 0; order.append(key)
		base[key] += w
	if any(KIND.match(s) and KIND.match(s).group(3) == NEW for key in order for s in key):
		return None
	out = []
	for key in order:
		out.append((key, base[key]))
		if any(KIND.match(s) and KIND.match(s).group(3) == TEMPLATE for s in key):
			ships = []
			for s in key:
				m = KIND.match(s)
				ships.append(new_ship(m.group(2), bool(m.group(4))) if m and m.group(3) == TEMPLATE else s)
			out.append((tuple(ships), base[key]))
	res = []
	for key, w in out:
		w *= LINES_BEFORE if any(is_exotic(s) for s in key) else LINES_BEFORE + 1
		res.append((w, list(key)))
	g = reduce(gcd, [w for w, _ in res])
	return [(w // g, ships) for w, ships in res]

def rewrite(path, find_regions):
	lines = open(path, encoding="utf8").read().split("\n")
	done = []
	for name, a, b, ind in reversed(find_regions(lines)):
		_, _, vs = parse_variants(lines, a, b, ind)
		nv = convert(vs)
		if nv is None:
			print("%s: has the %s line already, left alone" % (name, NEW)); continue
		first, last, _ = parse_variants(lines, a, b, ind)
		lines[first:last] = render(nv, ind)
		done.append(name)
	open(path, "w", encoding="utf8").write("\n".join(lines))
	return done

def fleet_regions(lines):
	r = []
	i = 0
	while i < len(lines):
		t = tok(lines[i]) if lines[i] and not lines[i][0].isspace() else None
		if t and t[0] == "fleet" and len(t) > 1 and t[1] in FLEETS:
			j = i + 1
			while j < len(lines) and (not lines[j] or lines[j][0].isspace()): j += 1
			r.append((t[1], i + 1, j, 1)); i = j; continue
		i += 1
	assert sorted(n for n, *_ in r) == sorted(FLEETS), r
	return r

def mission_regions(lines):
	r = []; mission = None
	for i, line in enumerate(lines):
		if line and not line[0].isspace():
			t = tok(line); mission = t[1] if t and t[0] == "mission" and len(t) > 1 else None
		elif mission in MISSIONS and line == "\t\tfleet":
			j = i + 1
			while j < len(lines) and (not lines[j].strip() or len(lines[j]) - len(lines[j].lstrip("\t")) > 2): j += 1
			_, _, vs = parse_variants(lines, i + 1, j, 3)
			if any(KIND.match(strip(s)) for _, ss in vs for s in ss):
				r.append((mission, i + 1, j, 3))
	assert sorted(n for n, *_ in r) == sorted(MISSIONS), r
	return r

def ship_variants():
	"""Copy the donor's variants of each kind and mark onto the new line."""
	text = open(SHIP_FILE, encoding="utf8").read()
	if BEGIN in text:
		a = text.index(BEGIN); b = text.index(END, a) + len(END)
		text = text[:a].rstrip("\n") + "\n\n" + text[b:].lstrip("\n")
	blocks = {}; cur = None
	for raw in text.split("\n"):
		if raw and not raw[0].isspace():
			cur = None
			if raw.startswith("ship "):
				t = tok(raw); cur = t[-1]; blocks[cur] = [raw]
		elif cur is not None:
			blocks[cur].append(raw)
	out = [BEGIN,
		"# The %s line: the %s on a %s (worn, rich, lead) or a %s (deep)," % (NEW, NEW_OUTFIT, HULL["Worn"], HULL["Deep"]),
		"# each the %s variant of that hull and kind with the %s swapped" % (DONOR, DONOR_OUTFIT),
		"# for it and loaded with %s." % ", ".join("%s x%d" % (o, n) for o, n in EXTRA)]
	for kind in ("Worn", "Rich", "Deep", "Lead"):
		for mk2 in ((False,) if kind == "Worn" else (False, True)):
			donor = "Drowned %s (%s, %s%s)" % (HULL[kind], kind, DONOR, " II" if mk2 else "")
			body = blocks[donor][1:]
			while body and not body[-1].strip(): body.pop()
			old = '\t\t"%s Mk %s"' % (DONOR_OUTFIT, "II" if mk2 else "I")
			assert body.count(old) == 1, (donor, body)
			k = body.index(old)
			body[k:k + 1] = ['\t\t"%s Mk %s"' % (NEW_OUTFIT, "II" if mk2 else "I")] + ['\t\t"%s" %d' % (o, n) for o, n in EXTRA]
			out.append("")
			out.append('ship "Drowned %s" "%s"' % (HULL[kind], new_ship(kind, mk2)))
			out += body
	out.append(END)
	anchor = "# Restless wrecks (v0.3, DESIGN.md section 15)"
	a = text.index(anchor)
	text = text[:a] + "\n".join(out) + "\n\n" + text[a:]
	open(SHIP_FILE, "w", encoding="utf8").write(text)

ship_variants()
print("fleets:", rewrite(FLEET_FILE, fleet_regions))
print("missions:", rewrite(MISSION_FILE, mission_regions))
